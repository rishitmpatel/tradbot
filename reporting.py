"""Plots and RESULTS.md."""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from walkforward import stitched_returns  # noqa: E402


def _pct(x, digits=1):
    return "n/a" if x is None or x != x else f"{100 * x:+.{digits}f}%"


def _plain(x, digits=0):
    return "n/a" if x is None or x != x else f"{100 * x:.{digits}f}%"


def _num(x, digits=2):
    return "n/a" if x is None or x != x else f"{x:.{digits}f}"


def plot_experiment(name: str, runs: list[dict], bench_runs: list[dict] | None, path: Path, initial: float) -> None:
    fig, ax = plt.subplots(figsize=(11, 5))
    seeds = sorted({r["seed"] for r in runs})
    for s in seeds:
        rets = stitched_returns(runs, s)
        if rets is not None:
            ax.plot((1 + rets).cumprod() * initial, lw=1.2, label=f"{name} seed {s}")
    if bench_runs:
        b = stitched_returns(bench_runs, 0)
        if b is not None:
            ax.plot((1 + b).cumprod() * initial, "k--", lw=1, label="buy & hold (same windows)")
    for r in runs:
        if r.get("status") != "ok":
            continue
        ax.axvline(pd.Timestamp(r["fold"]["val_start"]), color="grey", lw=0.4, alpha=0.4)
        if r["metrics"].get("dead"):
            ax.axvline(pd.Timestamp(r["metrics"]["death_date"]), color="red", lw=0.8, ls=":")
    ax.set_title(f"{name}: stitched walk-forward OUT-OF-SAMPLE equity (red dotted = a run died)")
    ax.set_ylabel("paper equity")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=90)
    plt.close(fig)


def plot_overview(series: dict[str, pd.Series], path: Path, initial: float, title: str) -> None:
    fig, ax = plt.subplots(figsize=(11, 6))
    for name, rets in series.items():
        style = "--" if name.startswith("baseline:") else "-"
        ax.plot((1 + rets).cumprod() * initial, style, lw=1.1, label=name)
    ax.set_title(title)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=90)
    plt.close(fig)


def _row(s: dict, verdict: str) -> str:
    return (f"| {s['name']} | {s.get('algo', '-')} | {s.get('status', 'ok')} | {s.get('n_ok', 0)}/{s.get('n_runs', 0)} "
            f"| {s.get('survived', 0)}/{s.get('n_ok', 0)} ({_plain(s.get('survival_rate'))}) "
            f"| {_pct(s.get('mean_return'))} | {_pct(s.get('min_return'))} | {_num(s.get('mean_sharpe'))} "
            f"| {_num(s.get('penalized_sharpe'))} | {_num(s.get('dsr_prob'))} | {_num(s.get('mean_sortino'))} "
            f"| {_plain(s.get('mean_stitched_mdd'), 1)} | {_num(s.get('mean_turnover'), 1)} | {verdict} |")


HEADER = ("| experiment | algo | status | runs ok | survived | OOS return (mean seeds) | worst seed | Sharpe | "
          "penalized Sharpe | DSR prob | Sortino | max DD (stitched) | turnover/yr | verdict |\n"
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")


def write_results_md(path: Path, ctx: dict) -> None:
    L = []
    synthetic = ctx["source"] == "synthetic"
    L.append("# RESULTS - quant-rl-bot walk-forward research\n")
    if synthetic:
        L.append("> **SYNTHETIC DATA - THESE ARE NOT REAL RESULTS.** Prices were generated by `synthetic_data.py` "
                 "only to test that the code runs. Nothing here says anything about real markets.\n")
    if ctx.get("smoke"):
        L.append("> **SMOKE RUN** (tiny training budget, few folds). Only checks that the pipeline works.\n")
    L.append("> Paper-trading research only. Validation (walk-forward out-of-sample) results; the locked test set "
             f"was **not** used here. {ctx['final_test_note']}\n")
    L.append(f"- Generated: {ctx['generated']}  \n- Data source: `{ctx['source']}`  \n"
             f"- Round: {ctx['round']}  \n- Variants tried (all rounds, used for Sharpe penalty): **{ctx['n_trials']}**  \n"
             f"- Development data ends: {ctx['dev_end']}; locked test set: {ctx['test_start']} -> {ctx['data_end']}  \n"
             f"- Costs: {ctx['cost_bps']:.0f} bps per unit traded (commission + slippage)  \n"
             f"- Survival rule: run DEAD if equity falls > {ctx['max_dd']:.0%} below its peak (start {ctx['initial']:,.0f})\n")

    L.append("## Verdict\n")
    if ctx["passing"]:
        L.append("Strategies passing ALL checks (validation + robustness): **" + ", ".join(ctx["passing"]) + "**  ")
        L.append(f"Selected for the one-time final test: **{ctx['selected']}** (run `python final_test.py`).\n")
    else:
        L.append("**NO STRATEGY PASSED.** No strategy met all of: positive OOS return after costs, penalized Sharpe "
                 f"> {ctx['pc']['min_penalized_sharpe']}, survival >= {ctx['pc']['min_survival_rate']:.0%}, and "
                 "robustness under 2x costs and other seeds. This is a normal, honest outcome.\n")
    if ctx["suspicious"]:
        L.append("**WARNING - suspiciously good results (assume bug/leakage until proven otherwise):** "
                 + ", ".join(ctx["suspicious"]) + "\n")

    L.append("## RL experiments (every variant, including failures)\n")
    L.append(HEADER)
    for s in ctx["experiments"]:
        L.append(_row(s, s.get("verdict", "")))
    L.append("\nColumns: *OOS return* = stitched walk-forward validation return after costs, mean over seeds. "
             "*Sharpe* = mean over seeds of the stitched OOS Sharpe. *Penalized Sharpe* = Sharpe minus the "
             "expected best-of-N Sharpe under no skill (N = variants tried). *DSR prob* = deflated Sharpe "
             "probability. *Survived* = walk-forward runs (fold x seed) that never hit the drawdown kill switch.\n")

    L.append("## Baselines (same windows, same costs, same survival rule; fixed textbook parameters)\n")
    L.append(HEADER)
    for s in ctx["baselines"]:
        L.append(_row(s, s.get("verdict", "benchmark")))
    L.append("")

    L.append("## Robustness (top validation candidates)\n")
    if not ctx["robustness"]:
        L.append("Not run.\n")
    else:
        L.append("| candidate | test | status | runs ok | survived | return | Sharpe | pass |\n|---|---|---|---|---|---|---|---|")
        for cand, tests in ctx["robustness"].items():
            for t, r in tests.items():
                s = r.get("summary") or {}
                L.append(f"| {cand} | {t} | {r.get('status')} | {s.get('n_ok', '-')}/{s.get('n_runs', '-')} | "
                         f"{s.get('survived', '-')}/{s.get('n_ok', '-')} | {_pct(s.get('mean_return'))} | "
                         f"{_num(s.get('mean_sharpe'))} | {r.get('pass', '-')} |")
        L.append("")

    L.append("## Why each RL experiment failed or passed\n")
    for s in ctx["experiments"]:
        reasons = s.get("reasons") or []
        L.append(f"- **{s['name']}**: " + ("PASS" if s.get("verdict") == "PASS" else "; ".join(reasons) or "-"))
        if s.get("errors"):
            L.append(f"  - errors: {s['errors'][:2]}")
    if ctx.get("skipped"):
        L.append(f"\nSkipped (over experiment cap of {ctx['cap']}): {', '.join(ctx['skipped'])}\n")

    L.append("\n## Walk-forward folds\n")
    L.append("| fold | train | validation |\n|---|---|---|")
    for f in ctx["folds"]:
        L.append(f"| {f.k} | {f.train_start} -> {f.train_end} | {f.val_start} -> {f.val_end} |")

    L.append("\n## Data quality\n")
    L.append("| ticker | rows | start | end | years | jumps > 25% (check splits) |\n|---|---|---|---|---|---|")
    for q in ctx["quality"]:
        L.append(f"| {q['ticker']} | {q['rows']} | {q['start']} | {q['end']} | {q['years']} | {', '.join(q['big_jumps']) or '-'} |")

    L.append("\n## Equity curves (out-of-sample, stitched)\n")
    L.append(f"![overview]({ctx['overview_plot']})\n")
    for name, p in ctx["plots"].items():
        L.append(f"### {name}\n![{name}]({p})\n")

    L.append("## Caveats\n")
    L.append("- Validation numbers are optimistic once you pick the best of many variants; the penalized Sharpe tries to "
             "correct for that but cannot fully.\n- Daily close-to-close fills, fixed proportional costs, no taxes, no "
             "borrow fees for shorts, no FX (Indian stocks are in INR, returns are currency-neutral here).\n"
             "- Yahoo adjusted prices can contain errors; see data-quality table.\n"
             "- Past performance does not predict future results. Paper trading only.\n")
    path.write_text("\n".join(L), encoding="utf-8")


def save_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, default=str), encoding="utf-8")
